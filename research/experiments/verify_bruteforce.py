#!/usr/bin/env python3
"""
Independent exact verifier for the d-dimensional shift-symmetry enumeration.

Purpose (route A03 of research/approaches.md): compare, with exact integer
arithmetic and no shared code with the plotting scripts,

  L1  definition-level brute force:
        |S| = #{ s : Z_n^d -> Sigma  |  exists v != 0 with s(u) = s(u+v) all u }
      by enumerating all sigma^(n^d) configurations and all n^d - 1 vectors.

  L2  subgroup-level inclusion-exclusion, independent of any closed formula:
      generators = one representative per cyclic subgroup of prime order,
      found by brute-force order computation in Z_n^d (NOT by projective
      coordinates); subgroup joins computed by BFS closure (NOT by rank
      formulas); |Fix(H)| = sigma^(n^d / |H|) because H acts freely by
      translation (cosets).  Requires only the completeness lemma, which is
      itself cross-checked against L1 on every L1-feasible case.

  L3  the draft paper's closed formula
        |S| = sum_{0 < v <= d} (-1)^(1+|v|) prod_i r_d(p_i,v_i) sigma^(n^d prod p_i^-v_i),
        r_d(p,v) = p^C(v,2) * gaussbinom(d,v)_p.

Also audited here:
  * the inclusion-exclusion coefficient identity
        sum_{J subset lines(F_p^d), rank(J)=r} (-1)^(|J|+1) = (-1)^(r+1) p^C(r,2) [d r]_p
    by direct enumeration of subsets of lines with Gaussian elimination mod p;
  * the draft's Theorem 5.1 lower bound (claimed for all n, d; equality iff n prime);
  * the draft's claim "local minima of P at primes, local maxima at even n > 4";
  * a counterexample to draft Theorem 3.2 (irreversibility) under the draft's
    literal Definition 2.2 (per-cell arbitrary neighborhood function).

Everything is exact integer arithmetic. Run:  python3 verify_bruteforce.py
"""

import itertools
import math
import sys
import platform
from fractions import Fraction

# ---------------------------------------------------------------- helpers

def prime_factors(n):
    fs, t, d = [], n, 2
    while d * d <= t:
        if t % d == 0:
            fs.append(d)
            while t % d == 0:
                t //= d
        d += 1
    if t > 1:
        fs.append(t)
    return fs

def is_prime(n):
    return n >= 2 and prime_factors(n) == [n]

def gaussian_binomial(d, r, p):
    if r < 0 or r > d:
        return 0
    num, den = 1, 1
    for i in range(r):
        num *= p ** (d - i) - 1
        den *= p ** (i + 1) - 1
    assert num % den == 0
    return num // den

# ---------------------------------------------------------------- L1: definition-level

def all_cells(n, d):
    return list(itertools.product(range(n), repeat=d))

def brute_force_count(n, d, sigma):
    """Enumerate all sigma^(n^d) configurations; count those fixed by some
    nonzero translation. Pure definition, no group theory."""
    cells = all_cells(n, d)
    N = len(cells)
    idx = {c: i for i, c in enumerate(cells)}
    perms = []
    for v in cells:
        if all(x == 0 for x in v):
            continue
        perms.append([idx[tuple((c[j] + v[j]) % n for j in range(d))] for c in cells])
    count = 0
    for s in itertools.product(range(sigma), repeat=N):
        for perm in perms:
            if all(s[i] == s[perm[i]] for i in range(N)):
                count += 1
                break
    return count

# ---------------------------------------------------------------- L2: subgroup inclusion-exclusion

def element_order(v, n, d):
    k, w = 1, v
    while any(x != 0 for x in w):
        w = tuple((w[j] + v[j]) % n for j in range(d))
        k += 1
    return k

def prime_order_generators(n, d):
    """One representative per cyclic subgroup of prime order in Z_n^d,
    found by brute force over all elements (independent of the projective
    parameterization used in the draft)."""
    reps, seen = [], set()
    for v in all_cells(n, d):
        if all(x == 0 for x in v):
            continue
        if not is_prime(element_order(v, n, d)):
            continue
        sub = frozenset(cyclic_subgroup(v, n, d))
        if sub not in seen:
            seen.add(sub)
            reps.append(v)
    return reps

def cyclic_subgroup(v, n, d):
    out, w = [], tuple([0] * d)
    while True:
        out.append(w)
        w = tuple((w[j] + v[j]) % n for j in range(d))
        if all(x == 0 for x in w):
            break
    return out

def closure(base, gen, n, d):
    """Subgroup generated by base (a frozenset subgroup) and one new element."""
    elems = set(base)
    frontier = [gen]
    while frontier:
        g = frontier.pop()
        if g in elems:
            continue
        add = set()
        for e in list(elems) + [g]:
            for f in list(elems) + [g]:
                s = tuple((e[j] + f[j]) % n for j in range(d))
                if s not in elems:
                    add.add(s)
        elems.add(g)
        frontier.extend(add)
    return frozenset(elems)

def ie_subgroup_count(n, d, sigma, max_gens=20, verbose=False):
    """|S| by inclusion-exclusion over ALL nonempty subsets of the prime-order
    generator representatives; join subgroups via cached BFS closure."""
    gens = prime_order_generators(n, d)
    if len(gens) > max_gens:
        return None, len(gens)
    N = n ** d
    trivial = frozenset([tuple([0] * d)])
    join_cache = {}
    pow_cache = {}

    def term_pow(h):
        if h not in pow_cache:
            assert N % h == 0, (n, d, h)
            pow_cache[h] = sigma ** (N // h)
        return pow_cache[h]

    total = 0
    stack = [(0, trivial, 0)]  # (next index, current subgroup, #chosen)
    while stack:
        i, sub, chosen = stack.pop()
        if i == len(gens):
            if chosen > 0:
                total += (-1) ** (chosen + 1) * term_pow(len(sub))
            continue
        stack.append((i + 1, sub, chosen))          # skip gens[i]
        key = (sub, gens[i])
        if key not in join_cache:
            join_cache[key] = closure(sub, gens[i], n, d)
        stack.append((i + 1, join_cache[key], chosen + 1))  # take gens[i]
    return total, len(gens)

# ---------------------------------------------------------------- L3: draft closed formula

def r_d(p, v, d):
    if v == 0:
        return 1
    return p ** (v * (v - 1) // 2) * gaussian_binomial(d, v, p)

def formula_count(n, d, sigma):
    ps = prime_factors(n)
    k = len(ps)
    if k == 0:
        return 0
    N = n ** d
    total = 0
    for vec in itertools.product(range(d + 1), repeat=k):
        if all(v == 0 for v in vec):
            continue
        coeff, div = 1, 1
        for p, v in zip(ps, vec):
            coeff *= r_d(p, v, d)
            div *= p ** v
        assert N % div == 0
        total += (-1) ** (1 + sum(vec)) * coeff * sigma ** (N // div)
    return total

# ---------------------------------------------------------------- coefficient identity audit

def rank_mod_p(vectors, p, d):
    rows = [list(v) for v in vectors]
    rank, col = 0, 0
    while rank < len(rows) and col < d:
        piv = next((r for r in range(rank, len(rows)) if rows[r][col] % p), None)
        if piv is None:
            col += 1
            continue
        rows[rank], rows[piv] = rows[piv], rows[rank]
        inv = pow(rows[rank][col], -1, p)
        rows[rank] = [(x * inv) % p for x in rows[rank]]
        for r in range(len(rows)):
            if r != rank and rows[r][col] % p:
                f = rows[r][col]
                rows[r] = [(a - f * b) % p for a, b in zip(rows[r], rows[rank])]
        rank += 1
        col += 1
    return rank

def lines_of(p, d):
    reps, seen = [], set()
    for v in itertools.product(range(p), repeat=d):
        if all(x == 0 for x in v):
            continue
        line = frozenset(tuple((c * x) % p for x in v) for c in range(1, p))
        if line not in seen:
            seen.add(line)
            reps.append(v)
    return reps

def audit_coefficients(p, d):
    """Enumerate all subsets of lines of F_p^d; group signed counts by rank of span;
    compare against (-1)^(r+1) p^C(r,2) [d r]_p."""
    ls = lines_of(p, d)
    acc = {}
    for mask in range(1, 1 << len(ls)):
        sub = [ls[i] for i in range(len(ls)) if mask >> i & 1]
        r = rank_mod_p(sub, p, d)
        acc[r] = acc.get(r, 0) + (-1) ** (len(sub) + 1)
    ok = True
    for r in range(1, d + 1):
        expected = (-1) ** (r + 1) * p ** (r * (r - 1) // 2) * gaussian_binomial(d, r, p)
        got = acc.get(r, 0)
        status = "OK" if got == expected else "MISMATCH"
        if got != expected:
            ok = False
        print(f"    p={p} d={d} r={r}: sum={got} expected={expected} {status}")
    return ok

# ---------------------------------------------------------------- bound + extrema audits

def draft_lower_bound(n, d, sigma):
    m = (n ** d - 1) // (n - 1) if n > 1 else 0
    return sigma ** (n ** (d - 1)) * m - sigma * (m - 1)

def log10_bigint(x):
    if x <= 0:
        return float("-inf")
    b = x.bit_length()
    if b <= 900:
        return math.log10(x)
    sh = b - 60
    return math.log10(x >> sh) + sh * math.log10(2)

def log10_prob(n, d, sigma):
    return log10_bigint(formula_count(n, d, sigma)) - n ** d * math.log10(sigma)

# ---------------------------------------------------------------- irreversibility counterexample

def irreversibility_counterexample():
    """Draft Definition 2.2 allows an ARBITRARY neighborhood function
    eta : cell x config -> Sigma^b with a shared phi. Under that literal
    definition, Theorem 3.2 is false. d=1, n=2, Sigma={0,1}, b=1:
      eta_0(s) = (s_0,)   eta_1(s) = (0,)   phi = identity.
    All cells share phi. s=(1,1) is fixed by v=1, Phi(s)=(1,0) is not."""
    def eta(i, s):
        return (s[0],) if i == 0 else (0,)
    phi = lambda t: t[0]
    s = (1, 1)
    assert s[0] == s[1]                       # s in S(v=1)
    out = tuple(phi(eta(i, s)) for i in range(2))
    print(f"    s = {s} (shift-symmetric by v=1),  Phi(s) = {out}")
    print(f"    Phi(s) symmetric by v=1?  {out[0] == out[1]}")
    return out[0] != out[1]

# ---------------------------------------------------------------- main

def main():
    print(f"python {sys.version.split()[0]} on {platform.platform()}")
    failures = []

    print("\n[1] Coefficient identity: subset-of-lines signed sums vs (-1)^(r+1) p^C(r,2) [d r]_p")
    for p, d in [(2, 2), (2, 3), (2, 4), (3, 2), (3, 3), (5, 2), (7, 2)]:
        if not audit_coefficients(p, d):
            failures.append(f"coefficient identity p={p} d={d}")

    print("\n[2] L1 (definition) vs L2 (subgroup IE) vs L3 (draft formula)")
    l1_cases = (
        [(n, 1, 2) for n in range(2, 15)] + [(n, 1, 3) for n in range(2, 9)]
        + [(2, 2, 2), (2, 2, 3), (2, 2, 4), (3, 2, 2), (3, 2, 3), (4, 2, 2),
           (2, 3, 2), (2, 3, 3), (2, 4, 2)]
    )
    for n, d, sigma in l1_cases:
        b = brute_force_count(n, d, sigma)
        ie, ng = ie_subgroup_count(n, d, sigma)
        f = formula_count(n, d, sigma)
        ok = b == ie == f
        print(f"    n={n} d={d} sigma={sigma}: L1={b} L2={ie} L3={f} |G|={ng} {'OK' if ok else 'MISMATCH'}")
        if not ok:
            failures.append(f"L1/L2/L3 n={n} d={d} sigma={sigma}: {b} {ie} {f}")

    print("\n[3] L2 vs L3 on larger cases (incl. multi-prime and prime powers)")
    l2_cases = [(5, 2, 2), (6, 2, 2), (6, 2, 3), (8, 2, 2), (9, 2, 2), (10, 2, 2),
                (12, 2, 2), (15, 2, 2), (30, 2, 2), (3, 3, 2), (4, 3, 2), (6, 3, 2),
                (2, 4, 2), (4, 4, 2), (6, 1, 2), (12, 1, 2), (30, 1, 2), (60, 1, 2)]
    for n, d, sigma in l2_cases:
        ie, ng = ie_subgroup_count(n, d, sigma)
        f = formula_count(n, d, sigma)
        if ie is None:
            print(f"    n={n} d={d} sigma={sigma}: skipped (|G|={ng} too large)")
            continue
        ok = ie == f
        print(f"    n={n} d={d} sigma={sigma}: L2={ie} L3={f} |G|={ng} {'OK' if ok else 'MISMATCH'}")
        if not ok:
            failures.append(f"L2/L3 n={n} d={d} sigma={sigma}: {ie} != {f}")

    print("\n[4] Stated reference values")
    refs = [(2, 2, 2, 8), (3, 2, 2, 26), (5, 2, 2, 182), (2, 3, 2, 72), (3, 3, 2, 6398)]
    for n, d, sigma, want in refs:
        got = formula_count(n, d, sigma)
        ok = got == want
        print(f"    n={n} d={d}: |S|={got} expected {want} {'OK' if ok else 'MISMATCH'}")
        if not ok:
            failures.append(f"reference n={n} d={d}: {got} != {want}")

    print("\n[5] Draft Theorem 5.1 lower bound audit: count >= bound? equality iff prime?")
    violations = 0
    for d in range(1, 5):
        for n in range(2, 13):
            for sigma in (2, 3):
                c = formula_count(n, d, sigma)
                lb = draft_lower_bound(n, d, sigma)
                if c < lb:
                    print(f"    BOUND VIOLATED: n={n} d={d} sigma={sigma}: |S|={c} < claimed lower bound {lb}")
                    violations += 1
                elif is_prime(n) and c != lb:
                    print(f"    EQUALITY FAILS AT PRIME: n={n} d={d} sigma={sigma}: |S|={c} != bound {lb}")
                    violations += 1
                elif (not is_prime(n)) and c == lb:
                    print(f"    UNEXPECTED EQUALITY AT COMPOSITE: n={n} d={d} sigma={sigma}")
                    violations += 1
    print(f"    total violations of draft Theorem 5.1: {violations}")
    if violations == 0:
        print("    (no violations found)")

    print("\n[6] 'Local minima at primes, local maxima at even n>4' audit (P uniform, sigma=2)")
    for d, nmax in [(2, 40), (3, 24), (4, 12)]:
        lp = {n: log10_prob(n, d, 2) for n in range(2, nmax + 2)}
        bad = []
        for n in range(4, nmax):
            if is_prime(n) and not (lp[n] < lp[n - 1] and lp[n] < lp[n + 1]):
                bad.append(f"prime n={n} not a local min")
            if n > 4 and n % 2 == 0 and not (lp[n] > lp[n - 1] and lp[n] > lp[n + 1]):
                bad.append(f"even n={n} not a local max")
        print(f"    d={d}, n<= {nmax}: " + ("all pattern claims hold" if not bad else "; ".join(bad)))
        for m in bad:
            failures.append(f"extrema pattern d={d}: {m}")

    print("\n[7] Irreversibility under the draft's literal Definition 2.2 (arbitrary per-cell eta)")
    if irreversibility_counterexample():
        print("    counterexample stands: draft Thm 3.2 needs translation-equivariant neighborhoods")
    else:
        failures.append("irreversibility counterexample failed to fire")

    print("\n" + "=" * 70)
    if failures:
        print(f"RESULT: {len(failures)} discrepancy group(s):")
        for f in failures:
            print("  -", f)
    else:
        print("RESULT: all cross-checks consistent (L1=L2=L3 wherever computed)")
    print("NOTE: [5] reports draft-theorem violations separately above; they are")
    print("findings about the draft, not verifier inconsistencies.")

if __name__ == "__main__":
    main()
