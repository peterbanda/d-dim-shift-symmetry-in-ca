#!/usr/bin/env python3
"""
Figure 1 of the paper (chart 17): example configurations, sigma = 2.

  (a) Z_6^2, stabilizer exactly <(3,0)>            (axis-parallel period)
  (b) Z_6^2, stabilizer exactly <(2,2)>            (diagonal translation of order 3)
  (c) Z_6^2, trivial stabilizer                    (not shift-symmetric)
  (d) Z_4^3, stabilizer exactly <(0,2,2)>          (three dimensions; active cells drawn)

Every stabilizer claimed in the caption is computed here by brute force over
all translations and asserted. The caption's count |S_{6^2}| = 801064 (sigma = 2)
is asserted twice: by the closed form of Theorem 4.4 (formula_count of
research/experiments/verify_bruteforce.py) and by an independent
inclusion-exclusion over the prime-order cyclic subgroups of Z_6^2.

Convention: a cell u = (u_1, u_2) is drawn in column u_1, row u_2 (row 0 at the
bottom); (tau_v s)(u) = s(u + v), so s is fixed by v iff s(u + v) = s(u) for all u.
Deterministic (fixed seeds). Run from the project root; writes
charts/chart17_example_configs.pdf.
"""

import itertools
import logging
import random
import sys

sys.path.insert(0, 'research/experiments')
from verify_bruteforce import formula_count

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.patches import Rectangle, FancyArrowPatch
import numpy as np

logging.getLogger('fontTools').setLevel(logging.ERROR)   # subsetting chatter

OUT = 'charts/chart17_example_configs.pdf'
ON = '#1f4e79'      # active cell
OFF = 'white'
ACC = '#d95f02'     # translation arrow and orbit outline


# ------------------------------------------------------------- group helpers

def cells(n, d):
    return list(itertools.product(range(n), repeat=d))


def add(u, v, n):
    return tuple((a + b) % n for a, b in zip(u, v))


def stabilizer(s, n, d):
    """All v with s(u + v) = s(u) for every u (brute force)."""
    return sorted(v for v in cells(n, d)
                  if all(s[add(u, v, n)] == s[u] for u in cells(n, d)))


def generated(gens, n, d):
    """Subgroup of Z_n^d generated by gens (closure under addition)."""
    zero = (0,) * d
    H = {zero}
    frontier = [zero]
    while frontier:
        new = []
        for h in frontier:
            for g in gens:
                x = add(h, g, n)
                if x not in H:
                    H.add(x)
                    new.append(x)
        frontier = new
    return H


def fill_from_orbits(n, d, v, rng, density=0.5, active_reps=None):
    """Configuration constant on the cosets of <v>: random by orbit, or the
    union of the orbits of active_reps."""
    H = generated([v], n, d)
    s = {}
    if active_reps is None:
        for u in cells(n, d):
            if u in s:
                continue
            val = 1 if rng.random() < density else 0
            for h in H:
                s[add(u, h, n)] = val
    else:
        s = {u: 0 for u in cells(n, d)}
        for u in active_reps:
            for h in H:
                s[add(u, h, n)] = 1
    return s


# ----------------------------------------------- independent count of S_{6^2}

def count_S_by_minimal_subgroups(n, d, sigma):
    """|S| = sum over nonempty sets J of prime-order cyclic subgroups of
    (-1)^{|J|+1} sigma^{N / |<union J>|}  (inclusion-exclusion over Fix(C))."""
    N = n ** d
    minimal = set()
    for v in cells(n, d):
        H = frozenset(generated([v], n, d))
        k = len(H)
        if k > 1 and all(k % q for q in range(2, k)):     # prime order
            minimal.add(H)
    minimal = list(minimal)
    total = 0
    for r in range(1, len(minimal) + 1):
        for J in itertools.combinations(minimal, r):
            gens = [g for C in J for g in C]
            total += (-1) ** (r + 1) * sigma ** (N // len(generated(gens, n, d)))
    return total, len(minimal)


# ------------------------------------------------------------------ drawing

def draw_2d(ax, s, n, v=None, mark=None, title=''):
    for (x, y), val in s.items():
        ax.add_patch(Rectangle((x, y), 1, 1, facecolor=ON if val else OFF,
                               edgecolor='#9a9a9a', linewidth=0.5))
    if mark is not None and v is not None:
        H = generated([v], n, 2)
        for h in H:
            x, y = add(mark, h, n)
            ax.add_patch(Rectangle((x + 0.06, y + 0.06), 0.88, 0.88, fill=False,
                                   edgecolor=ACC, linewidth=1.6))
        x0, y0 = mark
        x1, y1 = x0 + v[0], y0 + v[1]
        ax.add_patch(FancyArrowPatch((x0 + 0.5, y0 + 0.5), (x1 + 0.5, y1 + 0.5),
                                     arrowstyle='-|>', mutation_scale=11,
                                     color=ACC, linewidth=1.6, zorder=5))
    ax.set_xlim(0, n)
    ax.set_ylim(0, n)
    ax.set_aspect('equal')
    ax.set_xticks([])
    ax.set_yticks([])
    for sp in ax.spines.values():
        sp.set_linewidth(0.8)



def draw_3d(ax, s, n, v, mark, title=''):
    filled = np.zeros((n, n, n), dtype=bool)
    for (x, y, z), val in s.items():
        filled[x, y, z] = bool(val)
    ax.voxels(filled, facecolors=ON, edgecolors='#0b2740', linewidth=0.3, alpha=0.55)
    for axis in (ax.xaxis, ax.yaxis, ax.zaxis):
        axis.set_pane_color((1, 1, 1, 0))
        axis.line.set_color((1, 1, 1, 0))
    # wire frame of the torus box
    for a, b in itertools.product([0, n], repeat=2):
        ax.plot([0, n], [a, a], [b, b], color='#9a9a9a', linewidth=0.5)
        ax.plot([a, a], [0, n], [b, b], color='#9a9a9a', linewidth=0.5)
        ax.plot([a, a], [b, b], [0, n], color='#9a9a9a', linewidth=0.5)
    x0, y0, z0 = (c + 0.5 for c in mark)
    ax.quiver(x0, y0, z0, v[0], v[1], v[2], color=ACC, linewidth=2.0,
              arrow_length_ratio=0.2, zorder=10)
    ax.set_xlim(0, n)
    ax.set_ylim(0, n)
    ax.set_zlim(0, n)
    ax.set_box_aspect((1, 1, 1))
    ax.set_xticks([])
    ax.set_yticks([])
    ax.set_zticks([])
    ax.view_init(elev=20, azim=-62)


# --------------------------------------------------------------------- main

def main():
    report = {}

    # (a) Z_6^2, v = (3,0)
    rng = random.Random(17001)
    while True:
        sa = fill_from_orbits(6, 2, (3, 0), rng)
        if stabilizer(sa, 6, 2) == [(0, 0), (3, 0)]:
            break
    # (b) Z_6^2, v = (2,2)
    rng = random.Random(17002)
    while True:
        sb = fill_from_orbits(6, 2, (2, 2), rng)
        if stabilizer(sb, 6, 2) == [(0, 0), (2, 2), (4, 4)]:
            break
    # (c) Z_6^2, trivial stabilizer
    rng = random.Random(17003)
    while True:
        sc = {u: (1 if rng.random() < 0.5 else 0) for u in cells(6, 2)}
        if stabilizer(sc, 6, 2) == [(0, 0)]:
            break
    # (d) Z_4^3, v = (0,2,2), the orbits of three fixed cells (6 active cells)
    reps = [(0, 0, 0), (3, 1, 0), (2, 3, 1)]
    sd = fill_from_orbits(4, 3, (0, 2, 2), None, active_reps=reps)
    mark_d = (0, 0, 0)                                       # arrow (0,0,0) -> (0,2,2)

    stabs = {
        'a': stabilizer(sa, 6, 2), 'b': stabilizer(sb, 6, 2),
        'c': stabilizer(sc, 6, 2), 'd': stabilizer(sd, 4, 3),
    }
    assert stabs['a'] == [(0, 0), (3, 0)]
    assert stabs['b'] == [(0, 0), (2, 2), (4, 4)]
    assert stabs['c'] == [(0, 0)]
    assert stabs['d'] == [(0, 0, 0), (0, 2, 2)]

    # caption count |S_{6^2}| for sigma = 2, two independent ways
    closed = formula_count(6, 2, 2)
    ie, nmin = count_S_by_minimal_subgroups(6, 2, 2)
    assert closed == ie == 801064, (closed, ie)
    assert nmin == 3 + 4                                     # (p^d-1)/(p-1) for p = 2, 3

    plt.rcParams.update({'font.family': 'serif', 'mathtext.fontset': 'cm',
                         'pdf.fonttype': 42})
    fig = plt.figure(figsize=(6.6, 1.95))
    axs = [fig.add_axes([0.005 + 0.235 * i, 0.04, 0.21, 0.78]) for i in range(3)]
    draw_2d(axs[0], sa, 6, v=(3, 0), mark=(1, 4))
    draw_2d(axs[1], sb, 6, v=(2, 2), mark=(0, 0))
    draw_2d(axs[2], sc, 6)
    ax3 = fig.add_axes([0.715, -0.02, 0.28, 0.90], projection='3d')
    draw_3d(ax3, sd, 4, (0, 2, 2), mark_d)
    titles = [r'(a) $\mathrm{Stab}=\langle(3,0)\rangle$',
              r'(b) $\mathrm{Stab}=\langle(2,2)\rangle$',
              r'(c) $\mathrm{Stab}=\{0\}$',
              r'(d) $\mathrm{Stab}=\langle(0,2,2)\rangle$']
    for i, s in enumerate(titles):
        fig.text(0.11 + 0.235 * i if i < 3 else 0.855, 0.87, s, ha='center', fontsize=9)
    fig.savefig(OUT, metadata={'CreationDate': None, 'Creator': None, 'Producer': None})

    print('stabilizers:', stabs)
    print('mark (d):', mark_d, 'active cells (d):', sorted(u for u, x in sd.items() if x))
    print('|S_{6^2}| (sigma=2): closed form', closed, '| minimal-subgroup IE', ie,
          '| prime-order subgroups', nmin, '| fraction', closed / 2 ** 36)
    print('wrote', OUT)


if __name__ == '__main__':
    main()
